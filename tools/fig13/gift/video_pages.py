"""The gift and the construction as precomputed videos on the site: smooth on a phone, where drawing the films live stutters.

    python3 tools/fig13/gift/video_pages.py GIFT_DARK.mp4 GIFT_LIGHT.mp4 CONS_DARK.mp4 CONS_LIGHT.mp4 CATCH_DARK.mp4 CATCH_LIGHT.mp4

Encodes each master (rendered by render.cjs + ffmpeg at CRF 16) for the web: H.264 High, CRF 23, 30 frames per second, a key frame
every 2 s, moov atom first (plays while it loads), into public/simulations/fig13/video/{gift,construction}-{dark,light}.mp4, with a
poster frame each; then writes the two player pages:
    public/simulations/fig13/reem.html          the gift, then the construction, then the catch, then again from the start
    public/simulations/fig13/construction.html  the construction alone, looping
    public/simulations/fig13/catch.html         the catch alone (a motor takes the pendulum out of chaos onto the butterfly), looping
Each page follows the reader's light or dark setting (or ?theme=dark|light, or its Night / Paper buttons), plays muted and inline
so a phone starts it by itself, and shows its controls. The canvas renderers stay in tools/fig13/gift/ (reem.html, construction.html).
"""
import sys, subprocess, pathlib

ROOT = pathlib.Path(__file__).resolve().parents[3]
DST = ROOT / 'public/simulations/fig13'; VID = DST / 'video'; VID.mkdir(parents=True, exist_ok=True)
masters = dict(zip(['gift-dark', 'gift-light', 'construction-dark', 'construction-light', 'catch-dark', 'catch-light'], sys.argv[1:7]))
assert len(masters) == 6, __doc__
for name, src in masters.items():
    out = VID / (name + '.mp4')
    subprocess.run(['ffmpeg', '-y', '-loglevel', 'error', '-i', src, '-c:v', 'libx264', '-profile:v', 'high', '-level', '4.1', '-preset', 'slow',
                    '-crf', '23', '-r', '30', '-g', '60', '-pix_fmt', 'yuv420p', '-movflags', '+faststart', '-an', str(out)], check=True)
    subprocess.run(['ffmpeg', '-y', '-loglevel', 'error', '-ss', '0.5', '-i', str(out), '-frames:v', '1', '-q:v', '4', str(VID / (name + '.jpg'))], check=True)
    print('%-20s %5.1f MB' % (name, out.stat().st_size / 1e6))

ref = (ROOT / 'public/simulations/flower-hunt.html').read_text().split('\n')
CSP = next(l for l in ref if 'Content-Security-Policy' in l).strip()
REF = next(l for l in ref if 'name="referrer"' in l).strip()


def page(title, playlist, loop_all):
    return f'''<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="UTF-8">
{CSP}
{REF}
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>{title}</title>
<!-- Generated by tools/fig13/gift/video_pages.py; do not edit by hand. Precomputed videos of the Fig. 13 films (rendered from
     tools/fig13/gift/), played inline and muted so that a phone starts them by itself. -->
<style>
@font-face {{ font-family: 'IBM Plex Mono'; src: url(../../fonts/ibm-plex-mono/ibm-plex-mono-400-latin.woff2) format('woff2'); }}
:root {{ --bg:#140d10; --ink:#f5f1ea; --muted:#b9a59b; --chip:rgba(26,17,20,.82); --line:#3a2a2e; }}
@media (prefers-color-scheme: light) {{ :root:not([data-theme="dark"]) {{ --bg:#f5f1ea; --ink:#1c1518; --muted:#6f635d; --chip:rgba(255,250,243,.88); --line:#d9d0c2; }} }}
:root[data-theme="light"] {{ --bg:#f5f1ea; --ink:#1c1518; --muted:#6f635d; --chip:rgba(255,250,243,.88); --line:#d9d0c2; }}
html, body {{ margin:0; height:100%; background:var(--bg); overflow:hidden; }}
video {{ position:fixed; inset:0; width:100%; height:100%; object-fit:contain; background:var(--bg); }}
.bar {{ position:fixed; left:10px; right:10px; bottom:10px; display:flex; gap:8px; flex-wrap:wrap; font:13px 'IBM Plex Mono', monospace; z-index:2; }}
.bar a, .bar button {{ color:var(--muted); background:var(--chip); border:1px solid var(--line); border-radius:6px; padding:6px 10px; text-decoration:none; font:inherit; cursor:pointer; }}
.bar button.on {{ color:var(--ink); }}
</style>
</head>
<body>
<video id="v" playsinline muted autoplay preload="auto"></video>
<div class="bar">
  <a href="../butterfly-dashboard.html">← Fig. 13</a>
  <button type="button" id="night">Night</button><button type="button" id="paper">Paper</button>
  <button type="button" id="again">From the start</button>
</div>
<script>
'use strict';
const PLAYLIST = {playlist!r}, LOOP_ALL = {str(loop_all).lower()};
const v = document.getElementById('v'), Q = new URLSearchParams(location.search);
let theme = Q.get('theme') || (matchMedia('(prefers-color-scheme: light)').matches ? 'light' : 'dark'), k = 0;
function load(i, keepTime) {{
    k = i; const t = keepTime ? v.currentTime : 0;
    v.poster = 'video/' + PLAYLIST[k] + '-' + theme + '.jpg'; v.src = 'video/' + PLAYLIST[k] + '-' + theme + '.mp4';
    v.addEventListener('loadedmetadata', () => {{ if (t) v.currentTime = t; }}, {{ once: true }});
    v.play().catch(() => {{ v.controls = true; }});
}}
function setTheme(t) {{
    theme = t; document.documentElement.dataset.theme = t;
    document.getElementById('night').classList.toggle('on', t === 'dark'); document.getElementById('paper').classList.toggle('on', t === 'light');
    if (v.src) load(k, true);
}}
v.addEventListener('ended', () => {{ if (k + 1 < PLAYLIST.length) load(k + 1); else if (LOOP_ALL) load(0); }});
v.addEventListener('click', () => {{ v.paused ? v.play() : v.pause(); }});
document.getElementById('night').onclick = () => setTheme('dark');
document.getElementById('paper').onclick = () => setTheme('light');
document.getElementById('again').onclick = () => load(0);
setTheme(theme); load(0);
</script>
</body>
</html>
'''


(DST / 'reem.html').write_text(page('For رِيمْ', ['gift', 'construction', 'catch'], True))
(DST / 'construction.html').write_text(page('Constructing the butterfly by hand', ['construction'], True))
(DST / 'catch.html').write_text(page('Catching the butterfly', ['catch'], True))
print('wrote', DST / 'reem.html', DST / 'construction.html', 'and', DST / 'catch.html')
