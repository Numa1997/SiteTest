"""The whole gift as one film, drawn live in the browser: public/simulations/fig13/film.html.

Plays, one after the other, the three live films that publish_films.py copies into the site:
    live-gift.html          For رِيمْ and فَرَاشَتُكِ written by turning arrows, the butterfly by two arrows, its dashboard, the exact strike
    live-construction.html  the butterfly built by hand from its two perpendicular waveforms, the time axes joined by a mitre
    live-catch.html         a motor at the top pin takes the pendulum out of chaos, sets it on the butterfly, and lets go
Each film is opened with ?film=1 in a frame of 1080 x 1920 scaled to the screen; this page keeps the clock (30 frames a second) and
asks the film to draw frame f (window.renderFrame), so nothing is precomputed and no video file is needed (Cloudflare serves no
file above 25 MiB; the four-minute film as one MP4 is about 60 MB). Controls: play/pause (or tap the picture), previous, next,
from the start, Night/Paper, and a bar showing where you are in the whole film; it loops.

    python3 tools/fig13/gift/film_page.py
"""
import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[3]
ref = (ROOT / 'public/simulations/flower-hunt.html').read_text().split('\n')
CSP = next(l for l in ref if 'Content-Security-Policy' in l).strip()
REF = next(l for l in ref if 'name="referrer"' in l).strip()

PAGE = '''<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="UTF-8">
''' + CSP + '\n' + REF + '''
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>For رِيمْ: the whole film, live</title>
<!-- Generated by tools/fig13/gift/film_page.py; do not edit by hand. The three Fig. 13 gift films drawn live, one after the other. -->
<style>
@font-face { font-family: 'Instrument Sans'; src: url(fonts/instrument-sans-400.woff2) format('woff2'); }
:root { --bg:#140d10; --ink:#f5f1ea; --muted:#b9a59b; --chip:rgba(26,17,20,.82); --line:#3a2a2e; --accent:#e2a2aa; }
:root[data-theme="light"] { --bg:#f5f1ea; --ink:#1c1518; --muted:#6f635d; --chip:rgba(255,250,243,.9); --line:#d9d0c2; --accent:#7a1f2b; }
html, body { margin:0; height:100%; background:var(--bg); overflow:hidden; }
#box { position:fixed; left:0; top:0; width:1080px; height:1920px; transform-origin:0 0; }
iframe { width:1080px; height:1920px; border:0; display:block; background:var(--bg); }
#tap { position:fixed; inset:0 0 64px 0; z-index:1; }
.bar { position:fixed; left:10px; right:10px; bottom:10px; display:flex; gap:8px; align-items:center; flex-wrap:wrap; z-index:2;
       font:14px 'Instrument Sans', sans-serif; }
.bar a, .bar button { color:var(--muted); background:var(--chip); border:1px solid var(--line); border-radius:6px; padding:6px 10px;
       text-decoration:none; font:inherit; cursor:pointer; }
.bar button.on { color:var(--ink); }
#prog { flex:1 1 120px; height:6px; background:var(--chip); border:1px solid var(--line); border-radius:4px; position:relative; min-width:80px; }
#prog i { position:absolute; left:0; top:0; bottom:0; background:var(--accent); border-radius:4px; }
#prog b { position:absolute; top:-3px; bottom:-3px; width:1px; background:var(--muted); }
#lab { color:var(--muted); }
</style>
</head>
<body>
<div id="box"><iframe id="fr" title="film"></iframe></div>
<div id="tap"></div>
<div class="bar">
  <a href="../butterfly-dashboard.html">← Fig. 13</a>
  <button type="button" id="play">Pause</button><button type="button" id="prev">◀</button><button type="button" id="next">▶</button>
  <button type="button" id="again">From the start</button>
  <button type="button" id="night">Night</button><button type="button" id="paper">Paper</button>
  <span id="lab"></span><div id="prog"><i id="fill"></i></div>
</div>
<script>
'use strict';
const PARTS = [['live-gift.html', 'For رِيمْ'], ['live-construction.html', 'built by hand'], ['live-catch.html', 'caught and let go']];
const FPS = 30, fr = document.getElementById('fr'), Q = new URLSearchParams(location.search);
let theme = Q.get('theme') || (matchMedia('(prefers-color-scheme: light)').matches ? 'light' : 'dark');
let part = 0, f = 0, total = null, playing = true, last = null, lengths = [0, 0, 0];
function fit() {
    const cw = document.documentElement.clientWidth, ch = document.documentElement.clientHeight - document.querySelector('.bar').offsetHeight - 20, s = Math.min(cw / 1080, ch / 1920, 1);
    document.getElementById('box').style.transform = `translate(${Math.max(0, (cw - 1080 * s) / 2)}px, 0) scale(${s})`;
}
function load(k, frame) {
    part = (k + PARTS.length) % PARTS.length; f = frame || 0; total = null;
    fr.src = PARTS[part][0] + '?film=1&theme=' + theme;
}
fr.addEventListener('load', () => {
    const w = fr.contentWindow;
    const ready = () => { if (w.__ready && w.FILM) { total = w.FILM.frames(); lengths[part] = total; draw(); } else setTimeout(ready, 50); };
    ready();
});
function draw() {
    const w = fr.contentWindow; if (!total || !w.renderFrame) return;
    w.renderFrame(Math.min(f, total - 1));
    const known = lengths.every(x => x > 0), sum = lengths.reduce((a, b) => a + b, 0);
    let before = 0; for (let i = 0; i < part; i++) before += lengths[i];
    document.getElementById('fill').style.width = known ? (100 * (before + f) / sum) + '%' : (100 * (part + f / total) / PARTS.length) + '%';
    document.getElementById('lab').textContent = (part + 1) + ' / ' + PARTS.length + ' · ' + PARTS[part][1];
}
function tick(ts) {
    if (playing && total && (last === null || ts - last >= 1000 / FPS - 2)) {
        last = ts; f++;
        if (f >= total) load(part + 1); else draw();
    }
    requestAnimationFrame(tick);
}
function setTheme(t) {
    theme = t; document.documentElement.dataset.theme = t;
    document.getElementById('night').classList.toggle('on', t === 'dark'); document.getElementById('paper').classList.toggle('on', t === 'light');
}
function toggle() { playing = !playing; document.getElementById('play').textContent = playing ? 'Pause' : 'Play'; }
document.getElementById('play').onclick = toggle; document.getElementById('tap').onclick = toggle;
document.getElementById('prev').onclick = () => load(part - 1); document.getElementById('next').onclick = () => load(part + 1);
document.getElementById('again').onclick = () => load(0);
document.getElementById('night').onclick = () => { setTheme('dark'); load(part, f); };
document.getElementById('paper').onclick = () => { setTheme('light'); load(part, f); };
setTheme(theme); fit(); addEventListener('resize', fit); load(0); requestAnimationFrame(tick);
</script>
</body>
</html>
'''
(ROOT / 'public/simulations/fig13/film.html').write_text(PAGE)
print('wrote public/simulations/fig13/film.html')
