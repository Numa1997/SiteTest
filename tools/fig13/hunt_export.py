"""Write the flower-hunt results into public/scripts/fig13-hunt-data.js for the page flower-hunt.html.

Inputs (from hunt.py, hunt_inspect.py and butterfly.py, all in OUTDIR): delta_g0.npz, hunt.json, butterflies.json.
Kept in the garden:
  flowers    closed to 1e-8, petals point in k different directions (rejects the small ovals where the lower arm spins on
             its own and every 'petal' lands on the same spot), and inside the video's momentum range |p1| <= 35.6, |p2| <= 20;
  butterflies closed to 1e-8;
  one unstable flower, kept on purpose to show what an unstable orbit does on screen.
Usage: python3 tools/fig13/hunt_export.py OUTDIR public/scripts/fig13-hunt-data.js
"""
import sys, json, math
import numpy as np

out, dest = sys.argv[1], sys.argv[2]
g0 = np.load(out + '/delta_g0.npz')
hunt = json.load(open(out + '/hunt.json'))
bf = json.load(open(out + '/butterflies.json'))


def stability(tr):
    if abs(abs(tr) - 2) < 0.01:
        return 'neutral'
    return 'stable' if abs(tr) < 2 else 'unstable'


garden, seen = [], set()
for f in hunt['gravity_flowers']:
    k = f['k']
    dirs = {round(a) % 360 for a in f['petal_tip_angles_deg']}
    if len(dirs) != k or abs(f['p1']) > 35.6 or abs(f['p2']) > 20 or f['closure'] > 1e-8:
        continue
    key = (k, round(f['p1'], 3), round(f['p2'], 3))
    if key in seen:
        continue
    seen.add(key)
    garden.append(dict(kind='flower', k=k, p1=f['p1'], p2=f['p2'], period=f['period'], E=f['E'], trace=f['trace'],
                       stability=stability(f['trace'])))
KEEP_BUTTERFLIES = (12, 18, 24, 32)      # one unstable (N = 12) and three neutral, spread over the wing angles
KEEP_UNSTABLE_FLOWERS = 1               # keep one unstable flower on purpose; drop the others
uns = [g for g in garden if g['stability'] == 'unstable']
for g in uns[:-KEEP_UNSTABLE_FLOWERS]:
    garden.remove(g)
for b in bf['butterflies']:
    if b['k'] not in KEEP_BUTTERFLIES:
        continue
    garden.append(dict(kind='butterfly', k=b['k'], p1=b['p1'], p2=b['p2'], period=b['period'], E=b['E'], trace=b['trace'],
                       stability=stability(b['trace']), wing=b['wing_half_angle_deg']))
garden.sort(key=lambda g: (g['kind'] != 'flower', g['k'], g['p1']))

alpha = g0['alpha']; nu = g0['delta'] / (2 * math.pi)
step = 2                                                  # every second direction: 900 points over [0, pi)
theory = dict(alpha=[round(float(a), 5) for a in alpha[::step]],
              nu=[None if np.isnan(v) else round(float(v), 5) for v in nu[::step]])
targets = [dict(k=t['k'], q=t['q'], alpha=t['alpha']) for t in hunt['g0_flowers'] if t['k'] <= 8]
data = dict(made='tools/fig13/hunt.py, hunt_inspect.py, butterfly.py, hunt_export.py; equal uniform rods, m = 1 kg, l = 1 m, g = 9.8 m/s^2',
            theory=theory, targets=targets, garden=garden)
with open(dest, 'w') as fh:
    fh.write('/* Generated by tools/fig13/hunt_export.py: do not edit by hand. */\nwindow.FIG13_HUNT = ')
    json.dump(data, fh, separators=(',', ':'))
    fh.write(';\n')
print('garden:', len(garden), 'tiles:', [(g['kind'], g['k'], round(g['p1'], 2), round(g['p2'], 2), g['stability']) for g in garden])
