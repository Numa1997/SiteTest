"""Modes of the sculpted Guinness glass for a range of fills -> public/scripts/slosh-modes.js (format 3, three-dimensional).

Run: python3 tools/fig12/build_modes3d.py public/scripts/slosh-modes.js [quick]
For each fill V and each kept mode: m (dominant azimuthal number), o ('c' or 's': cos- or sin-type, i.e. along x or along y
for m = 1), n, lam [1/m], the forcing coefficients Qx, Qy [m] (translation), Qrx, Qry [m^2] (rotation about x or y through
the foot centre), N = int psi^2 dS [m^2], Iw/E, Ib/E, Is/E, E/lam, the purity (share of the rim energy in the dominant
component), and the surface shape as theta-Fourier components (cos and sin) at the radial nodes s_j for k in m, m+-2.
For two fills also the velocity potential and its gradient in the same representation on the (s, z) node grid.
Mode shapes are normalised to max |psi| = 1 on the rim. Also per fill: the liquid volume and the Stokes-Joukowski
inertias J_rx, J_ry (per unit density) of the frozen liquid turning about x or y through the foot centre.
"""
import sys, os, json, time, numpy as np
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import modes3d, geom as G
out = sys.argv[1]; quick = len(sys.argv) > 2 and sys.argv[2] == 'quick'
NS, NT, NZ = (6, 24, 16) if quick else (8, 28, 18)
zf = G.Z_F / 1000
Rfun = lambda z, th: G.R_inner(z * 1000, th) / 1000
VOLS = list(range(300, 571, 20)) + [576]; FIELD_VOLS = [500, 568]
if 568 not in VOLS: VOLS = sorted(VOLS + [500, 568])
VOLS = sorted(set(VOLS + [500, 568]))
hs = np.arange(G.Z_F + 1, G.H + 1e-9, 0.25); Vs = np.array([G.cavity_volume(h, nz=401, nt=64) for h in hs])
KEEP_M = 3; NMODES = 14
data = dict(format=3, source='tools/fig12/build_modes3d.py; geometry tools/fig12/geom.py', g_note='lam = omega^2/g; shapes: max |psi| = 1 on the rim',
            vols_mL=VOLS, field_vols_mL=FIELD_VOLS, s_nodes=np.linspace(0, 1, 2 * NS + 1).round(6).tolist(), fills=[])
t_all = time.time()
for V in VOLS:
    zs = float(np.interp(V * 1e3, Vs, hs)) / 1000
    t0 = time.time()
    M, md, chis, rig = modes3d.solve(Rfun, zf, zs, nmodes=NMODES + 6, Ns=NS, Nt=NT, Nz=NZ)
    a = float(G.R_inner(zs * 1000, np.pi / 2)) / 1000
    F = dict(V_mL=V, zs=round(zs, 6), a=round(a, 6), V_liq=round(rig['V'], 9), J_rx=rig['Jsj']['rx'], J_ry=rig['Jsj']['ry'], modes=[])
    if V in FIELD_VOLS:
        zl = list(range(0, 2 * NZ + 1, 2)); F['field_z'] = [round(float(M.Z[k]), 6) for k in zl]
    counts = {}
    for x in md:
        m, o, pur = modes3d.label(M, x['Phi'])
        if m > KEEP_M: continue
        n = counts.get((m, o), 0) + 1; counts[(m, o)] = n
        ks = [k for k in (m - 2, m, m + 2) if 0 <= k <= 6]
        sc = modes3d.surface_components(M, x['Phi'], ks)
        R = dict(m=m, o=o, n=n, lam=round(x['lam'], 5), Qx=round(x['Qx'], 7), Qy=round(x['Qy'], 7), Qrx=round(x['Qrx'], 8), Qry=round(x['Qry'], 8),
                 N=round(x['N'], 9), Iw=round(x['Iw'] / x['E'], 4), Ib=round(x['Ib'] / x['E'], 5), Is=round(x['Is'] / x['E'], 4),
                 E_over_lam=round(x['E'] / x['lam'], 7), pur=round(pur, 4),
                 psi={str(k): [np.round(sc[k][0], 5).tolist(), np.round(sc[k][1], 5).tolist()] for k in ks})
        if V in FIELD_VOLS:
            fc = modes3d.field_components(M, x['Phi'], ks, zl)
            R['field'] = {str(k): np.round(fc[k], 4).tolist() for k in ks}
        F['modes'].append(R)
        if len(F['modes']) == NMODES: break
    data['fills'].append(F)
    w = [r for r in F['modes'] if r['m'] == 1 and r['n'] == 1]
    fx = [r for r in w if r['o'] == 'c']; fy = [r for r in w if r['o'] == 's']
    print(f"V {V} mL: zs {zs*1e3:6.2f} mm, a {a*1e3:5.2f} mm, {M.n} nodes, {time.time()-t0:.0f} s; (1,1) along x {np.sqrt(9.81*fx[0]['lam'])/2/np.pi:.4f} Hz, along y {np.sqrt(9.81*fy[0]['lam'])/2/np.pi:.4f} Hz, "
          f"Qx {fx[0]['Qx']:.5f}, Qry {fx[0]['Qry']:.6f}, purity {fx[0]['pur']:.3f}; modes kept {[(r['m'], r['o'], r['n']) for r in F['modes']]}", flush=True)
zz = np.arange(0, G.H + 1e-9, 2.0)
data['glass'] = dict(source='dimensions.com elevation scaled to 160 x 85 mm; panels estimated from photographs', H_mm=G.H, floor_mm=G.Z_F, wall_mm=G.T_W,
                     V_brim_mL=round(G.cavity_volume(G.H) / 1e3, 1), z_mm=zz.tolist(), R_outer_mm=np.round(G.R0(zz), 3).tolist(),
                     R_inner_mm=[None if z < G.Z_F else round(float(v), 3) for z, v in zip(zz, G.R_inner(zz, np.pi / 2))],
                     panel=dict(A_mm=G.A_PANEL, W_crease_deg=float(np.degrees(G.W_CREASE)), z_V0=G.Z_V0, z_V1=G.Z_V1, z_fade0=G.Z_FADE0, z_V2=G.Z_V2))
js = '/* Generated by tools/fig12/build_modes3d.py (geometry: tools/fig12/geom.py). Do not edit by hand. */\nwindow.SLOSH_MODES = ' + json.dumps(data, separators=(',', ':')) + ';\n'
open(out, 'w').write(js); print('wrote', out, len(js), 'bytes;', f'{(time.time()-t_all)/60:.1f} min')
