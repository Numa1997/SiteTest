"""Modes of the Guinness tulip glass for a range of fills -> public/scripts/slosh-modes.js

Run: python3 tools/fig12/build_modes.py tools/fig12/glass_profile.json public/scripts/slosh-modes.js
For each fill volume V (300..590 mL, every 10 mL) and each mode (m, n) kept by the page:
  lam [1/m] (omega^2 = g lam), the surface shape f(r) normalised to f = 1 at the wall,
  Q = int f r^2 dr / int f^2 r dr (m = 1: how strongly a sideways acceleration drives the mode),
  Iw/E, Ib/E, Is/E (wall, floor and surface integrals of the tangential gradient over the energy integral).
For six fills it also stores Phi, Phi_r, Phi_z on a 12 x 20 grid in the meridional plane (velocity field).
"""
import sys, json, numpy as np
sys.path.insert(0, 'tools/fig12'); import modes
prof = json.load(open(sys.argv[1])); out = sys.argv[2]
z = np.array(prof['z_mm'])/1000; Ri = np.array([np.nan if v is None else v for v in prof['R_inner_mm']])/1000
zf = prof['floor_mm']/1000; m_ = ~np.isnan(Ri); Rfun = lambda q: np.interp(q, z[m_], Ri[m_])
def vol(h):
    q = np.linspace(zf, h, 2000); return np.trapezoid(np.pi*Rfun(q)**2, q)
KEEP = {0: 2, 1: 3, 2: 2, 3: 1}
VOLS = list(range(300, 591, 10)); FIELD_VOLS = [360, 420, 480, 520, 560, 590]
NS, NZ = 12, 20
data = dict(source='tools/fig12/build_modes.py; profile ' + prof['source'], g_note='lam = omega^2/g',
            keep=[[m, n] for m in KEEP for n in range(1, KEEP[m]+1)], vols_mL=VOLS, field_vols_mL=FIELD_VOLS,
            field_grid=dict(ns=NS, nz=NZ, note='s = r/R_i(z) in [0,1] (j = 0..ns-1); depth d_i = D (i/(nz-1))^1.6 below the surface, D = zs - floor'),
            fills=[])
for V in VOLS:
    lo, hi = zf, prof['H_mm']/1000
    for _ in range(60):
        mid = 0.5*(lo+hi); lo, hi = (mid, hi) if vol(mid) < V*1e-6 else (lo, mid)
    zs = 0.5*(lo+hi); a = float(Rfun(zs)); slope = float(np.gradient(Rfun(z[m_]), z[m_])[np.searchsorted(z[m_], zs)])
    F = dict(V_mL=V, zs=round(zs, 6), a=round(a, 6), wall_slope=round(slope, 4), modes=[])
    for m, nk in KEEP.items():
        X, T, idx, res = modes.solve(Rfun, zf, zs, m, nk, 16, 40)
        for n, md in enumerate(res, 1):
            I = modes.integrals(X, T, idx, md, Rfun, zf, zs)
            c = 1.0/md['f'][-1]                       # wall-normalised: f(a) = 1
            rs = md['rs']; fr = np.linspace(0, a, 25); fv = np.interp(fr, rs, md['f']*c)
            N = modes.surf_int(rs, md['f'], lambda r: r) if False else 1.0   # int f^2 r dr = 1 before scaling
            Q = (I['Px']*c)/(N*c*c) if m == 1 else 0.0
            M = dict(m=m, n=n, lam=round(md['lam'], 5), Q=round(Q, 7), Iw=round(I['Iw']/I['E'], 4), Ib=round(I['Ib']/I['E'], 5),
                     Is=round(I['Is']/I['E'], 4), E_over_lam=round(I['E']/md['lam'], 6), f=[round(v, 5) for v in fv])
            if V in FIELD_VOLS:
                D = zs - zf; pts = []
                for i in range(NZ):
                    zz = zs - D*(i/(NZ-1))**1.6 - (1e-7 if i == 0 else 0) + (1e-7 if i == NZ-1 else 0)
                    for j in range(NS):
                        pts.append((max(1e-7, Rfun(zz)*(j/(NS-1))*(1-2e-3)), zz))   # 0.2 % inside: the mesh wall is made of straight chords
                G = modes.grad_at(X, T, md['Phi']*c, np.array(pts))
                assert np.isfinite(G).all(), f'field point outside the mesh at V = {V}, mode {m},{n}'
                M['field'] = [round(float(v), 5) for v in G.ravel()]
            F['modes'].append(M)
    data['fills'].append(F)
    w = [M for M in F['modes'] if M['m'] == 1 and M['n'] == 1][0]
    print(f"V {V} mL: zs {zs*1e3:6.2f} mm, a {a*1e3:5.2f} mm, slope {slope:+.3f}; f11 {np.sqrt(9.81*w['lam'])/2/np.pi:.4f} Hz, Q {w['Q']:.5f} m, Iw/E {w['Iw']:.2f}", flush=True)
z = prof['z_mm']; kk = list(range(0, len(z), 4))
data['glass'] = dict(source=prof['source'], H_mm=prof['H_mm'], floor_mm=prof['floor_mm'], wall_mm=prof['wall_mm'], V_brim_mL=prof['V_brim_mL'],
                     z_mm=[z[i] for i in kk], R_outer_mm=[prof['R_outer_mm'][i] for i in kk], R_inner_mm=[prof['R_inner_mm'][i] for i in kk])
js = '/* Generated by tools/fig12/build_modes.py from tools/fig12/glass_profile.json. Do not edit by hand. */\nwindow.SLOSH_MODES = ' + json.dumps(data, separators=(',', ':')) + ';\n'
open(out, 'w').write(js); print('wrote', out, len(js), 'bytes')
