"""Writes public/_redirects: the short address of every page, served without a round trip (docs/usul.md, docs/performance.md).

Since 31 October 2026 phyeinusul.com runs with "html_handling": "none" (wrangler.jsonc): Cloudflare serves x.html at once, where
before it answered every x.html with a 307 to x, one round trip on every click (every link of the site names the .html file).
With "none" Cloudflare no longer finds a page at its short address (x, folder/, /), which readers have seen in the address bar
and shared since 20 October 2026. This file serves each page there too, as a 200 "proxy" rule (Cloudflare's _redirects,
https://developers.cloudflare.com/workers/static-assets/redirects/); a folder without its slash, and a page with one, is sent on with a
307, as before.

    python3 tools/redirects.py           writes public/_redirects
    python3 tools/redirects.py --check   writes nothing; exits 1 if public/_redirects is not what this script would write

Run it after adding, renaming or removing a page. Names with spaces are written with %20 (a space separates the fields).
Cloudflare allows 2,000 static rules; the site uses about 100.
"""
import pathlib
import sys
import urllib.parse

ROOT = pathlib.Path(__file__).resolve().parent.parent
PUBLIC = ROOT / 'public'
OUT = PUBLIC / '_redirects'


def rules():
    q = urllib.parse.quote
    out = ['# Generated by tools/redirects.py; do not edit by hand. Each page at the short address readers have used since',
           '# 20 October 2026, served without a round trip (wrangler.jsonc sets "html_handling": "none"; see docs/usul.md).',
           '/ /index.html 200']
    for f in sorted(PUBLIC.rglob('*.html')):
        rel = '/' + f.relative_to(PUBLIC).as_posix()
        if f.name == 'index.html':
            folder = rel[:-len('index.html')]
            if folder != '/':
                out += [f'{q(folder)} {q(rel)} 200', f'{q(folder[:-1])} {q(folder)} 307']
        else:
            short = rel[:-len('.html')]
            out += [f'{q(short)} {q(rel)} 200', f'{q(short)}/ {q(short)} 307']
    return '\n'.join(out) + '\n'


if __name__ == '__main__':
    text = rules()
    if '--check' in sys.argv:
        if not OUT.exists() or OUT.read_text() != text:
            print('public/_redirects is out of date: run python3 tools/redirects.py')
            sys.exit(1)
        print(f'public/_redirects: {text.count(chr(10)) - 2} rules, up to date')
    else:
        OUT.write_text(text)
        print(f'public/_redirects: {text.count(chr(10)) - 2} rules written')
