#!/usr/bin/env node
// Turns an export of the list into SQL for D1.
//
//   node tools/to-sql.mjs <export.json> > private/import.sql                  marks and added postings only (the default)
//   node tools/to-sql.mjs <export.json> --replace-list > private/import.sql   also REPLACES postings, meta and the e-mail log
//   npx wrangler d1 execute stellenrecherche --remote --file=private/import.sql
//
// The export is one JSON object: { postings, meta, applicationLog, marks, added }
// (meta as an object or as [{ key, value }], marks and added as arrays). It is
// what the AppDeploy app serves at /api/dossier and /api/marks (README.md, "Moving
// the real records"). Real records go to private/, which git ignores: they must
// never enter this public repository.
//
// The SQL replaces the whole list (postings, meta, log) and inserts marks and
// added postings that are not in the database yet; it never overwrites a mark
// made on the Cloudflare page. Every value is checked first; on the first bad
// record the script stops and names it, and prints no SQL.
//
// Older marks without an `outcome` field are given one, read the way the page
// always read them: a stage means Applied, the removed flag Not relevant.
import { readFileSync } from 'node:fs';
import { CATEGORY_KEYS, AREA_KEYS } from '../src/catalog.js';
import { validItem, validAddedId, validPatch } from '../src/validate.js';

// The list rules in German, written for this version (the English originals are in the export's meta).
export const RULES_DE = {
  rule_de: 'Jede Stelle nennt Physik oder Naturwissenschaften als zugelassenen Abschluss, akzeptiert einen Bachelor, richtet sich nicht an Studierende oder Promovierende und verlinkt auf die Seite des Arbeitgebers selbst. In der Produktionsleitung zählen geforderte Berufs- und Führungserfahrung nicht, denn diese Erfahrung ist vorhanden; in allen anderen Bereichen bleiben Stellen nur für Erfahrene außen vor. KI-Training heißt: KI an Aufgaben aus Physik und Mathematik trainieren oder ihre Lösungen bewerten. Content-Erstellung schließt Schulunterricht aus. Prüf- und Messtechnik umfasst Stellen, deren eigentliches Ergebnis eine Messung, ein Prüfergebnis, eine Kalibrierung oder die Qualifizierung eines Geräts ist, oder der Prüfstand, der dies liefert.',
  rule_eu_de: 'Europa ohne Deutschland. Jede Stelle nennt Physik oder Naturwissenschaften als zugelassenen Abschluss, akzeptiert einen Bachelor, richtet sich nicht an Studierende oder Promovierende, verlinkt auf die Seite des Arbeitgebers und stammt von einem Arbeitgeber, der international einstellt: Die Anzeige bietet Unterstützung bei Visum, Arbeitserlaubnis oder Umzug, oder der Arbeitgeber steht im amtlichen Register des Landes (Niederlande: IND, Vereinigtes Königreich: Home Office, Dänemark: SIRI, Irland: Liste der Arbeitserlaubnisse). Arbeitssprache ist Englisch oder Deutsch, oder die Landessprache wird im Arbeitsalltag nicht verlangt. In der Produktionsleitung zählen geforderte Berufs- und Führungserfahrung nicht; in allen anderen Bereichen bleiben Stellen nur für Erfahrene außen vor.',
};

const q = v => (v === null || v === undefined ? 'NULL' : typeof v === 'number' ? String(v) : "'" + String(v).replace(/'/g, "''") + "'");
const fail = msg => { throw new Error(msg); };
const str = (v, max, where, required = false) => {
  if (v === null || v === undefined || v === '') { if (required) fail(where + ': missing'); return null; }
  if (typeof v !== 'string' || v.length > max) fail(where + ': not a string of at most ' + max + ' characters');
  return v;
};
const day = (v, where) => { if (v == null || v === '') return null; if (!/^\d{4}-\d{2}-\d{2}$/.test(v)) fail(where + ': not YYYY-MM-DD'); return v; };

const POSTING_KEYS = ['n', 'title', 'title_original', 'company', 'city', 'location_group', 'category', 'employment', 'url',
  'eligibility_quote_de', 'eligibility_en', 'salary', 'note', 'note_de', 'added_on', 'removed_on', 'removed_why',
  // carried in older exports, not stored:
  'target_category', 'starred', 'skills', 'duplicate_of', 'direct_employer_link', 'sort_order', 'location_label', 'category_label'];

export function toSql(exp, { replaceList = false } = {}) {
  const out = ['-- Generated by tools/to-sql.mjs. Contains real records: keep out of git.'];
  const postings = exp.postings ?? fail('export: no postings');
  const seen = new Set();
  const rows = [];
  for (const p of postings) {
    const w = 'posting ' + p?.n;
    if (!Number.isSafeInteger(p?.n) || p.n <= 0 || seen.has(p.n)) fail(w + ': bad or duplicate n');
    seen.add(p.n);
    for (const k of Object.keys(p)) if (!POSTING_KEYS.includes(k)) fail(w + ': unknown field ' + k);
    if (!CATEGORY_KEYS.includes(p.category)) fail(w + ': unknown category ' + p.category);
    if (!AREA_KEYS.includes(p.location_group)) fail(w + ': unknown area ' + p.location_group);
    let url; try { url = new URL(p.url); } catch { fail(w + ': bad url'); }
    if (!['https:', 'http:'].includes(url.protocol)) fail(w + ': url is not http(s)');
    // employment is a code (EMPLOYEE, CONTRACT, TRAINEE, TEMPORARY) or the ad's own words; the page shows a code's label, else the words.
    rows.push([p.n, str(p.title, 300, w + ' title', true), str(p.title_original, 300, w + ' title_original'), str(p.company, 300, w + ' company', true),
      str(p.city, 300, w + ' city'), p.location_group, p.category, str(p.employment, 300, w + ' employment'), p.url,
      str(p.eligibility_quote_de, 2000, w + ' quote'), str(p.eligibility_en, 2000, w + ' eligibility_en'), str(p.salary, 300, w + ' salary'),
      str(p.note, 5000, w + ' note'), str(p.note_de, 5000, w + ' note_de'), day(p.added_on, w + ' added_on'), day(p.removed_on, w + ' removed_on'),
      str(p.removed_why, 2000, w + ' removed_why')]);
  }
  // The list itself (postings, meta, e-mail log) is replaced only on request (--replace-list): the live database is kept up
  // to date every day, and the e-mail log is also fed by the Gmail pipeline (src/mail.js), so a plain import must not wipe it.
  const listOut = replaceList ? out : [];
  listOut.push('delete from postings;');
  for (const r of rows) listOut.push('insert into postings (n, title, title_original, company, city, location_group, category, employment, url, eligibility_quote_de, eligibility_en, salary, note, note_de, added_on, removed_on, removed_why) values (' + r.map(q).join(', ') + ');');

  const metaRows = Array.isArray(exp.meta) ? exp.meta.filter(r => !r._end).map(r => [r.key, r.value]) : Object.entries(exp.meta ?? {});
  const meta = new Map(metaRows);
  for (const [k, v] of Object.entries(RULES_DE)) if (!meta.has(k)) meta.set(k, v);
  if (exp.log_updated && !meta.has('log_updated')) meta.set('log_updated', exp.log_updated);
  listOut.push('delete from meta;');
  for (const [k, v] of meta) {
    if (typeof k !== 'string' || !k) fail('meta: bad key');
    listOut.push('insert into meta (key, value) values (' + q(k) + ', ' + q(JSON.stringify(v)) + ');');
  }

  const log = (exp.applicationLog ?? []).filter(r => !r._end);
  const ids = new Set();
  listOut.push('delete from application_log;');
  for (const r of log) {
    const w = 'log ' + r?.id;
    if (typeof r?.id !== 'string' || !r.id || ids.has(r.id)) fail(w + ': bad or duplicate id');
    ids.add(r.id);
    if (!Array.isArray(r.cards) || r.cards.some(n => !seen.has(n))) fail(w + ': cards must be card numbers on the list');
    if (!['rejected', 'confirmed', 'interview', 'portal_invitation', 'unclear'].includes(r.status)) fail(w + ': unknown status');
    listOut.push('insert into application_log (id, cards, company, title, status, date, note, source) values (' +
      [r.id, JSON.stringify(r.cards), r.company ?? '', r.title ?? '', r.status, day(r.date, w + ' date') ?? '', r.note ?? '', r.source ?? ''].map(q).join(', ') + ');');
  }

  for (const m of exp.marks ?? []) {
    const w = 'mark ' + m?.item_id;
    if (!validItem(m?.item_id)) fail(w + ': bad item_id');
    const { item_id, updated_at, id: _storeId, ...fields } = m;
    if (!Object.hasOwn(fields, 'outcome')) fields.outcome = fields.stage ? 'applied' : fields.removed ? 'not_relevant' : null;
    if (!validPatch(fields)) fail(w + ': fields do not pass the server check');
    const removed = fields.removed === undefined || fields.removed === null ? null : fields.removed ? 1 : 0;
    out.push('insert or ignore into marks (item_id, outcome, outcome_at, stage, stage_at, round, removed, note, snapshot, updated_at) values (' +
      [item_id, fields.outcome, fields.outcome_at ?? null, fields.stage ?? null, fields.stage_at ?? null, fields.round ?? null, removed,
        fields.note ?? null, fields.snapshot ? JSON.stringify(fields.snapshot) : null, updated_at ?? new Date().toISOString()].map(q).join(', ') + ');');
  }

  for (const a of exp.added ?? []) {
    const w = 'added ' + a?.item_id;
    if (!validAddedId(a?.item_id)) fail(w + ': bad item_id');
    if (!CATEGORY_KEYS.includes(a.category) || !AREA_KEYS.includes(a.area)) fail(w + ': unknown category or area');
    out.push('insert or ignore into added (item_id, url, title, company, city, area, category, added_at) values (' +
      [a.item_id, str(a.url, 2000, w + ' url', true), str(a.title, 300, w + ' title', true), a.company ?? '', str(a.city, 120, w + ' city', true),
        a.area, a.category, str(a.added_at, 40, w + ' added_at', true)].map(q).join(', ') + ');');
  }
  return out.join('\n') + '\n';
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const file = process.argv[2];
  if (!file) { console.error('usage: node tools/to-sql.mjs <export.json> [--replace-list]'); process.exit(2); }
  try { process.stdout.write(toSql(JSON.parse(readFileSync(file, 'utf8')), { replaceList: process.argv.includes('--replace-list') })); }
  catch (e) { console.error('Stopped, no SQL written: ' + e.message); process.exit(1); }
}
